//! Writes the Rust module for a protocol.

use super::{Arg, Interface, Kind, Message, Protocol};
use std::fmt::Write;

/// How the module is written.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Options {
    /// The path of this crate as the generated code names it: `::wayland`
    /// for a crate that depends on it (the default).
    pub runtime: String,
    /// Modules whose interfaces the protocol refers to, each imported with
    /// a glob: for a protocol that mentions `wl_surface`,
    /// `::wayland::protocol::wayland`.
    pub imports: Vec<String>,
    /// Where the XML came from (file, upstream version), for the header
    /// comment. One line.
    pub source: String,
}

impl Default for Options {
    fn default() -> Options {
        Options {
            runtime: "::wayland".to_string(),
            imports: Vec::new(),
            source: String::new(),
        }
    }
}

/// Words Rust keeps for itself; a protocol name that is one gets a `_`.
const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
    // Names the generated functions use themselves.
    "conn", "msg_", "ev",
];

/// `name` as a Rust identifier.
fn ident(name: &str) -> String {
    if KEYWORDS.contains(&name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

/// `wl_data_offer` as `WlDataOffer`.
fn camel(name: &str) -> String {
    let mut out = String::new();
    for part in name.split('_') {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.push(first.to_ascii_uppercase());
            out.push_str(chars.as_str());
        }
    }
    if out.is_empty() || out == "Self" || out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

/// An enum entry as a constant's name: `flipped_90` as `FLIPPED_90`, `90`
/// as `_90`.
fn constant(name: &str) -> String {
    let upper = name.to_ascii_uppercase();
    if upper.starts_with(|c: char| c.is_ascii_digit()) {
        format!("_{upper}")
    } else {
        upper
    }
}

fn kind_name(kind: Kind) -> &'static str {
    match kind {
        Kind::Int => "Int",
        Kind::Uint => "Uint",
        Kind::Fixed => "Fixed",
        Kind::String => "String",
        Kind::Object => "Object",
        Kind::NewId => "NewId",
        Kind::Array => "Array",
        Kind::Fd => "Fd",
    }
}

/// Writes the Rust module for `protocol`: for each interface a module with
/// its message tables, an object type whose methods send its requests, an
/// `Event` enum with a decoder, and its enums as constants.
///
/// The output is meant to be a file of its own, used as a module. It is
/// not passed through rustfmt; declare the module `#[rustfmt::skip]`.
pub fn generate(protocol: &Protocol, options: &Options) -> String {
    let rt = options.runtime.as_str();
    let mut o = String::new();
    // Writing to a String cannot fail.
    macro_rules! w {
        ($($t:tt)*) => {{ let _ = writeln!(o, $($t)*); }};
    }
    let source = match options.source.lines().next() {
        Some(s) if !s.trim().is_empty() => format!(" ({})", s.trim()),
        _ => String::new(),
    };
    w!(
        "// Generated by wayland::scan from the `{}` protocol{source}. Do not edit.",
        protocol.name
    );
    w!("// Carries the protocol's interface names, opcodes, argument types and enum");
    w!("// values only; none of its descriptive text.");
    w!();
    w!("#![allow(unused_mut, clippy::too_many_arguments, clippy::module_inception, clippy::match_single_binding)]");
    w!();
    for import in &options.imports {
        w!("#[allow(unused_imports)]");
        w!("use {import}::*;");
    }
    if !options.imports.is_empty() {
        w!();
    }
    for i in &protocol.interfaces {
        w!("pub use {}::{};", ident(&i.name), camel(&i.name));
    }
    for i in &protocol.interfaces {
        w!();
        interface(&mut o, rt, i);
    }
    o
}

fn table(o: &mut String, rt: &str, label: &str, messages: &[Message]) {
    macro_rules! w {
        ($($t:tt)*) => {{ let _ = writeln!(o, $($t)*); }};
    }
    if messages.is_empty() {
        w!("        {label}: &[],");
        return;
    }
    w!("        {label}: &[");
    for m in messages {
        if m.args.is_empty() {
            w!(
                "            {rt}::wire::Message {{ name: \"{}\", since: {}, destructor: {}, args: &[] }},",
                m.name, m.since, m.destructor
            );
            continue;
        }
        w!(
            "            {rt}::wire::Message {{ name: \"{}\", since: {}, destructor: {}, args: &[",
            m.name,
            m.since,
            m.destructor
        );
        for a in &m.args {
            let interface = match &a.interface {
                Some(i) => format!("Some(&super::{}::INTERFACE)", ident(i)),
                None => "None".to_string(),
            };
            w!(
                "                {rt}::wire::ArgDesc {{ kind: {rt}::wire::Kind::{}, nullable: {}, interface: {interface} }},",
                kind_name(a.kind), a.nullable
            );
        }
        w!("            ] }},");
    }
    w!("        ],");
}

/// The parameter a request takes for `a`, if it takes one.
fn parameter(rt: &str, a: &Arg, generic: &str) -> Option<String> {
    let name = ident(&a.name);
    let ty = match (a.kind, &a.interface, a.nullable) {
        (Kind::Int, ..) => "i32".to_string(),
        (Kind::Uint, ..) => "u32".to_string(),
        (Kind::Fixed, ..) => format!("{rt}::wire::Fixed"),
        (Kind::String, _, false) => "&str".to_string(),
        (Kind::String, _, true) => "Option<&str>".to_string(),
        (Kind::Object, Some(i), false) => camel(i),
        (Kind::Object, Some(i), true) => format!("Option<{}>", camel(i)),
        (Kind::Object, None, _) => "u32".to_string(),
        (Kind::NewId, Some(_), _) => return None,
        (Kind::NewId, None, _) => return Some(format!("{generic}: u32")),
        (Kind::Array, ..) => "&[u8]".to_string(),
        (Kind::Fd, ..) => "std::os::fd::BorrowedFd<'_>".to_string(),
    };
    Some(format!("{name}: {ty}"))
}

fn request(o: &mut String, rt: &str, i: &Interface, opcode: usize, m: &Message) {
    macro_rules! w {
        ($($t:tt)*) => {{ let _ = writeln!(o, $($t)*); }};
    }
    // Each untyped new id makes the method generic over the object bound,
    // and takes the version to bind beside it.
    let untyped: Vec<&Arg> = m
        .args
        .iter()
        .filter(|a| a.kind == Kind::NewId && a.interface.is_none())
        .collect();
    let generic = |a: &Arg| -> (String, String) {
        let n = untyped
            .iter()
            .position(|u| std::ptr::eq(*u, a))
            .unwrap_or(0);
        if untyped.len() == 1 {
            let taken = m.args.iter().any(|x| x.name == "version");
            let version = if taken { "bind_version" } else { "version" };
            ("T".to_string(), version.to_string())
        } else {
            (format!("T{n}"), format!("{}_version", ident(&a.name)))
        }
    };
    let mut params = String::new();
    let mut returns = Vec::new();
    for a in &m.args {
        let (ty, version) = generic(a);
        if let Some(p) = parameter(rt, a, &version) {
            let _ = write!(params, ", {p}");
        }
        if a.kind == Kind::NewId {
            returns.push(match &a.interface {
                Some(i) => camel(i),
                None => ty,
            });
        }
    }
    let generics = match untyped.len() {
        0 => String::new(),
        1 => format!("<T: {rt}::Proxy>"),
        n => {
            let list: Vec<String> = (0..n).map(|k| format!("T{k}: {rt}::Proxy")).collect();
            format!("<{}>", list.join(", "))
        }
    };
    let returned = match returns.len() {
        0 => "()".to_string(),
        1 => returns[0].clone(),
        _ => format!("({})", returns.join(", ")),
    };
    let what = if m.destructor {
        "; the object is gone afterwards"
    } else {
        ""
    };
    w!("        /// Sends `{}.{}`{what}.", i.name, m.name);
    if m.since > 1 {
        w!("        /// Since version {}.", m.since);
    }
    w!(
        "        pub fn {}{generics}(&self, conn: &mut {rt}::Connection{params}) -> Result<{returned}, {rt}::Error> {{",
        ident(&m.name)
    );
    w!("            let mut msg_ = conn.request(self.0, {opcode});");
    let mut made = Vec::new();
    for a in &m.args {
        let name = ident(&a.name);
        match (a.kind, &a.interface, a.nullable) {
            (Kind::Int, ..) => w!("            msg_.int({name});"),
            (Kind::Uint, ..) | (Kind::Object, None, _) => w!("            msg_.uint({name});"),
            (Kind::Fixed, ..) => w!("            msg_.fixed({name});"),
            (Kind::String, _, false) => w!("            msg_.string(Some({name}));"),
            (Kind::String, _, true) => w!("            msg_.string({name});"),
            (Kind::Object, Some(_), false) => {
                w!("            msg_.uint({rt}::Proxy::id(&{name}));")
            }
            (Kind::Object, Some(_), true) => {
                w!("            msg_.uint({name}.map_or(0, |o| {rt}::Proxy::id(&o)));")
            }
            (Kind::NewId, Some(target), _) => {
                w!(
                    "            let {name} = msg_.new_id(&super::{}::INTERFACE);",
                    ident(target)
                );
                made.push(name);
            }
            (Kind::NewId, None, _) => {
                let (ty, version) = generic(a);
                w!("            let {name} = msg_.new_id_bound(<{ty} as {rt}::Proxy>::interface(), {version});");
                made.push(name);
            }
            (Kind::Array, ..) => w!("            msg_.array({name});"),
            (Kind::Fd, ..) => w!("            msg_.fd({name});"),
        }
    }
    if m.destructor {
        w!("            msg_.send_destructor()?;");
    } else {
        w!("            msg_.send()?;");
    }
    let made: Vec<String> = made
        .iter()
        .map(|n| format!("{rt}::Proxy::from_id({n})"))
        .collect();
    match made.len() {
        0 => w!("            Ok(())"),
        1 => w!("            Ok({})", made[0]),
        _ => w!("            Ok(({}))", made.join(", ")),
    }
    w!("        }}");
}

/// The type an event carries for `a`, and the call that reads it.
fn field(rt: &str, a: &Arg) -> (String, String) {
    let (ty, read) = match (a.kind, &a.interface, a.nullable) {
        (Kind::Int, ..) => ("i32".to_string(), "ev.int()?".to_string()),
        (Kind::Uint, ..) | (Kind::Object, None, _) | (Kind::NewId, None, _) => {
            ("u32".to_string(), "ev.uint()?".to_string())
        }
        (Kind::Fixed, ..) => (format!("{rt}::wire::Fixed"), "ev.fixed()?".to_string()),
        (Kind::String, _, false) => ("String".to_string(), "ev.string()?".to_string()),
        (Kind::String, _, true) => ("Option<String>".to_string(), "ev.string_opt()?".to_string()),
        (Kind::Object, Some(i), true) => (
            format!("Option<{}>", camel(i)),
            "ev.object_opt()?".to_string(),
        ),
        (Kind::Object | Kind::NewId, Some(i), _) => (camel(i), "ev.object()?".to_string()),
        (Kind::Array, ..) => ("Vec<u8>".to_string(), "ev.array()?".to_string()),
        (Kind::Fd, ..) => ("std::os::fd::OwnedFd".to_string(), "ev.fd()?".to_string()),
    };
    (ty, read)
}

fn interface(o: &mut String, rt: &str, i: &Interface) {
    macro_rules! w {
        ($($t:tt)*) => {{ let _ = writeln!(o, $($t)*); }};
    }
    let module = ident(&i.name);
    let object = camel(&i.name);
    w!("/// The `{}` interface, version {}.", i.name, i.version);
    w!("pub mod {module} {{");
    w!("    #[allow(unused_imports)]");
    w!("    use super::*;");
    w!();
    w!("    /// The interface's requests and events as the wire has them.");
    w!("    pub static INTERFACE: {rt}::wire::Interface = {rt}::wire::Interface {{");
    w!("        name: \"{}\",", i.name);
    w!("        version: {},", i.version);
    table(o, rt, "requests", &i.requests);
    table(o, rt, "events", &i.events);
    w!("    }};");
    w!();
    w!("    /// A `{}` object: its id.", i.name);
    w!("    #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
    w!("    pub struct {object}(u32);");
    w!();
    w!("    impl {rt}::Proxy for {object} {{");
    w!("        fn interface() -> &'static {rt}::wire::Interface {{");
    w!("            &INTERFACE");
    w!("        }}");
    w!("        fn id(&self) -> u32 {{");
    w!("            self.0");
    w!("        }}");
    w!("        fn from_id(id: u32) -> Self {{");
    w!("            {object}(id)");
    w!("        }}");
    w!("    }}");
    if !i.requests.is_empty() {
        w!();
        w!("    impl {object} {{");
        for (opcode, m) in i.requests.iter().enumerate() {
            if opcode > 0 {
                w!();
            }
            request(o, rt, i, opcode, m);
        }
        w!("    }}");
    }
    w!();
    w!("    /// An event from a `{}`.", i.name);
    w!("    #[derive(Debug)]");
    w!("    pub enum Event {{");
    for m in &i.events {
        w!(
            "        /// `{}.{}`{}",
            i.name,
            m.name,
            if m.since > 1 {
                format!(", since version {}.", m.since)
            } else {
                ".".to_string()
            }
        );
        if m.args.is_empty() {
            w!("        {},", camel(&m.name));
            continue;
        }
        w!("        {} {{", camel(&m.name));
        for a in &m.args {
            w!("            /// `{}`", a.name);
            w!("            {}: {},", ident(&a.name), field(rt, a).0);
        }
        w!("        }},");
    }
    w!("    }}");
    w!();
    w!("    impl Event {{");
    w!("        /// Decodes an event of an object of this interface.");
    w!("        pub fn decode(mut ev: {rt}::Event) -> Result<Event, {rt}::Error> {{");
    w!("            ev.expect(&INTERFACE)?;");
    w!("            match ev.opcode {{");
    for (opcode, m) in i.events.iter().enumerate() {
        if m.args.is_empty() {
            w!("                {opcode} => Ok(Event::{}),", camel(&m.name));
            continue;
        }
        w!(
            "                {opcode} => Ok(Event::{} {{",
            camel(&m.name)
        );
        for a in &m.args {
            w!(
                "                    {}: {},",
                ident(&a.name),
                field(rt, a).1
            );
        }
        w!("                }}),");
    }
    w!("                op => Err({rt}::Error::Wire({rt}::wire::WireError::UnknownOpcode(op))),");
    w!("            }}");
    w!("        }}");
    w!("    }}");
    let since = |prefix: &str, messages: &[Message], o: &mut String| {
        for m in messages.iter().filter(|m| m.since > 1) {
            let _ = writeln!(o);
            let _ = writeln!(
                o,
                "    /// The version of `{}` that introduced `{}`.",
                i.name, m.name
            );
            let _ = writeln!(
                o,
                "    pub const {prefix}_{}_SINCE: u32 = {};",
                m.name.to_ascii_uppercase(),
                m.since
            );
        }
    };
    since("REQ", &i.requests, o);
    since("EVT", &i.events, o);
    for e in &i.enums {
        w!();
        w!(
            "    /// The `{}.{}` {}.",
            i.name,
            e.name,
            if e.bitfield { "bits" } else { "enum" }
        );
        w!("    pub mod {} {{", ident(&e.name));
        for entry in &e.entries {
            w!(
                "        /// `{}`{}",
                entry.name,
                if entry.since > 1 {
                    format!(", since version {}.", entry.since)
                } else {
                    ".".to_string()
                }
            );
            let value = if e.bitfield {
                format!("{:#x}", entry.value)
            } else {
                entry.value.to_string()
            };
            w!(
                "        pub const {}: u32 = {value};",
                constant(&entry.name)
            );
        }
        w!("    }}");
    }
    w!("}}");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_become_rust_identifiers() {
        assert_eq!(camel("wl_data_offer"), "WlDataOffer");
        assert_eq!(camel("zwp_linux_dmabuf_v1"), "ZwpLinuxDmabufV1");
        assert_eq!(camel("self"), "_Self");
        assert_eq!(camel("_"), "_");
        assert_eq!(ident("move"), "move_");
        assert_eq!(ident("type"), "type_");
        assert_eq!(ident("conn"), "conn_");
        assert_eq!(ident("surface"), "surface");
        assert_eq!(constant("flipped_90"), "FLIPPED_90");
        assert_eq!(constant("90"), "_90");
    }

    #[test]
    fn the_header_names_the_source_and_carries_one_line_of_it() {
        let p = Protocol {
            name: "empty".into(),
            interfaces: Vec::new(),
        };
        let mut options = Options {
            source: "empty.xml, v1\nand a second line".into(),
            ..Options::default()
        };
        let code = generate(&p, &options);
        assert!(code.starts_with(
            "// Generated by wayland::scan from the `empty` protocol (empty.xml, v1). Do not edit.\n"
        ));
        assert!(!code.contains("second line"));
        options.imports = vec!["crate::protocol::wayland".into()];
        assert!(generate(&p, &options).contains("use crate::protocol::wayland::*;\n"));
    }
}
